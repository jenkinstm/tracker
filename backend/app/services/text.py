"""Нормализация поисковых фраз."""

from __future__ import annotations

import re

_SPACES = re.compile(r"[\s\u00a0]+")


def normalize_phrase(phrase: str) -> str:
    """Нижний регистр, схлопнутые пробелы, обрезанные края.

    По этому значению строится уникальность внутри проекта: «Купить  ОКНА » и «купить окна»
    — одна и та же фраза, платить за неё дважды незачем. «ё» сводим к «е» по той же причине:
    Вордстат и выдача их не различают, а два снимка на одну фразу стоят вдвое дороже.
    """
    cleaned = _SPACES.sub(" ", (phrase or "").replace(" ", " ")).strip().lower()
    return cleaned.replace("ё", "е")
